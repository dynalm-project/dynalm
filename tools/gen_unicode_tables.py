#!/usr/bin/env python3
"""Generates dynalm/src/tokenizer/unicode_tables.inc from Python's unicodedata.

Emits sorted, merged code-point ranges for the categories the pre-tokenizers
need: letters (\\p{L}), numbers (\\p{N}), White_Space (\\s), and the two
case classes of the GPT-4o (o200k) regex: [\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}]
and [\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}].

    PYTHONUTF8=1 python tools/gen_unicode_tables.py > dynalm/src/tokenizer/unicode_tables.inc

The categories come from Python's unicodedata, or from a UnicodeData.txt of a
given version when Python's is different (the tables are Unicode 15.0.0):

    python tools/gen_unicode_tables.py --ucd UnicodeData.txt --version 15.0.0 > ...
"""
import sys
import unicodedata

# Unicode White_Space property (PropList.txt); regex \s in the Rust regex /
# Oniguruma engines used by HF tokenizers matches exactly this set.
WHITE_SPACE = [
    (0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0),
    (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
    (0x205F, 0x205F), (0x3000, 0x3000),
]


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"// {len(rs)} ranges")
    print(f"inline constexpr CodepointRange {name}[] = {{")
    line = "   "
    for a, b in rs:
        item = f" {{0x{a:X}, 0x{b:X}}},"
        if len(line) + len(item) > 98:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};\n")


def ucd_categories(path):
    """General category per code point from UnicodeData.txt (absent: Cn)."""
    cats = {}
    first = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split(";")
            cp, name, gc = int(fields[0], 16), fields[1], fields[2]
            if name.endswith(", First>"):
                first = cp
            elif name.endswith(", Last>"):
                for c in range(first, cp + 1):
                    cats[c] = gc
            else:
                cats[cp] = gc
    return lambda cp: cats.get(cp, "Cn")


def main():
    args = sys.argv[1:]
    if "--ucd" in args:
        cat = ucd_categories(args[args.index("--ucd") + 1])
        version = args[args.index("--version") + 1] if "--version" in args else "(UnicodeData.txt)"
    else:
        cat = lambda cp: unicodedata.category(chr(cp))
        version = unicodedata.unidata_version
    print(f"// Generated by tools/gen_unicode_tables.py from Unicode {version}.")
    print("// Do not edit.\n")
    emit("kLetterRanges", ranges(lambda cp: cat(cp).startswith("L")))
    emit("kNumberRanges", ranges(lambda cp: cat(cp).startswith("N")))
    emit("kWhitespaceRanges", WHITE_SPACE)
    emit("kUpperClassRanges", ranges(lambda cp: cat(cp) in ("Lu", "Lt", "Lm", "Lo") or cat(cp).startswith("M")))
    emit("kLowerClassRanges", ranges(lambda cp: cat(cp) in ("Ll", "Lm", "Lo") or cat(cp).startswith("M")))


if __name__ == "__main__":
    sys.exit(main())
